create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 username text not null unique,
 display_name text not null,
 role text not null default 'player' check (role in ('player','president')),
 created_at timestamptz not null default now()
);
create table if not exists public.disciplinary_records (
 id bigint generated by default as identity primary key,
 player_id uuid not null references public.profiles(id) on delete cascade,
 record_type text not null check (record_type in ('warning','suspension')),
 record_date date not null default current_date,
 reason text not null,
 games_suspended integer not null default 0 check (games_suspended >= 0 and games_suspended <= 100),
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create index if not exists disciplinary_records_player_date_idx on public.disciplinary_records(player_id, record_date desc);
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
declare u text; n text; begin
 u:=lower(coalesce(new.raw_user_meta_data->>'username','jogador'));
 n:=coalesce(new.raw_user_meta_data->>'display_name','Jogador');
 if u !~ '^[a-z0-9_]{3,24}$' then u:='jogador_'||substr(replace(new.id::text,'-',''),1,12); end if;
 insert into public.profiles(id,username,display_name,role) values(new.id,u,n,'player') on conflict(id) do nothing;
 return new; end; $$;
drop trigger if exists on_auth_user_created_matadores on auth.users;
create trigger on_auth_user_created_matadores after insert on auth.users for each row execute procedure public.handle_new_user();
create or replace function public.is_matadores_president() returns boolean language sql stable security definer set search_path = '' as $$
 select exists(select 1 from public.profiles where id=(select auth.uid()) and role='president'); $$;
alter table public.profiles enable row level security;
alter table public.disciplinary_records enable row level security;
drop policy if exists "profiles read own or president" on public.profiles;
create policy "profiles read own or president" on public.profiles for select to authenticated using(id=(select auth.uid()) or public.is_matadores_president());
drop policy if exists "profiles update president only" on public.profiles;
create policy "profiles update president only" on public.profiles for update to authenticated using(public.is_matadores_president()) with check(public.is_matadores_president());
drop policy if exists "records read own or president" on public.disciplinary_records;
create policy "records read own or president" on public.disciplinary_records for select to authenticated using(player_id=(select auth.uid()) or public.is_matadores_president());
drop policy if exists "president inserts records" on public.disciplinary_records;
create policy "president inserts records" on public.disciplinary_records for insert to authenticated with check(public.is_matadores_president());
drop policy if exists "president updates records" on public.disciplinary_records;
create policy "president updates records" on public.disciplinary_records for update to authenticated using(public.is_matadores_president()) with check(public.is_matadores_president());
drop policy if exists "president deletes records" on public.disciplinary_records;
create policy "president deletes records" on public.disciplinary_records for delete to authenticated using(public.is_matadores_president());
